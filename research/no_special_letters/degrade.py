# -*- coding: utf-8 -*-
"""Калмыцкий без спецбукв: как портят, как узнать, как восстановить.

Модуль без зависимостей от бота. Три части:
  * degrade(word, style)  — испортить правильное слово так, как пишут люди;
  * restore_candidates(w) — какие правильные слова могли дать такую запись;
  * триггеры — признаки, что слово/текст точно написаны без спецбукв.
"""
import random
import re
import unicodedata

SPECIAL = set('әөүһҗң')
VOWELS = set('аәеэиоөуүыяюё')
CONS = set('бвгджзйклмнпрстфхцчшщһҗң')

# Буквы-двойники из других алфавитов и латиницы. Выглядят как калмыцкие (или
# как их привычная замена) — пользователь их не отличает, мы обязаны.
LOOKALIKE = {
    # һ
    'h': 'һ', 'H': 'Һ', 'ҳ': 'һ', 'Ҳ': 'Һ', 'ғ': 'һ', 'Ғ': 'Һ',
    # ә
    'ə': 'ә', 'Ə': 'Ә', 'ӓ': 'ә', 'Ӓ': 'Ә', 'ä': 'ә', 'Ä': 'Ә', 'ǝ': 'ә',
    # ө
    'ӧ': 'ө', 'Ӧ': 'Ө', 'ö': 'ө', 'Ö': 'Ө', 'ɵ': 'ө', 'Ɵ': 'Ө', 'ѳ': 'ө', 'Ѳ': 'Ө',
    # ү
    'ӱ': 'ү', 'Ӱ': 'Ү', 'ü': 'ү', 'Ü': 'Ү', 'ұ': 'ү', 'Ұ': 'Ү', 'Y': 'Ү',
    # җ
    'ҷ': 'җ', 'Ҷ': 'Җ', 'ӂ': 'җ', 'Ӂ': 'Җ', 'ӝ': 'җ', 'Ӝ': 'Җ',
    # ң
    'ҥ': 'ң', 'Ҥ': 'Ң', 'ӈ': 'ң', 'Ӈ': 'Ң', 'ŋ': 'ң', 'Ŋ': 'Ң', 'ӊ': 'ң', 'Ӊ': 'Ң',
}
# Латиница, неотличимая от кириллицы на глаз: попадает из английской раскладки
# (h обычно тянет за собой соседей) или из автозамены.
LATIN_TWINS = {'a': 'а', 'e': 'е', 'o': 'о', 'p': 'р', 'c': 'с', 'x': 'х',
               'y': 'у', 'k': 'к', 'm': 'м', 't': 'т', 'b': 'в', 'A': 'А',
               'E': 'Е', 'O': 'О', 'P': 'Р', 'C': 'С', 'X': 'Х', 'K': 'К',
               'M': 'М', 'T': 'Т', 'B': 'В', 'y': 'у'}


# --------------------------------------------------------------------------
# Порча
# --------------------------------------------------------------------------
# Как ведут себя люди — по логам бота и по текстам в сети (см. отчёт):
#   ә: бәәдл->бяядл, сән->сян, келнәт->келнят, гергтәвт->гергтявт — «я» после
#      согласной; Үвләс->Увлэс — «э»; иногда просто «а».
#   ө: йөрәл->йорял — «о»; төвкнүн->тёвкнюн — «ё» после согласной.
#   ү: күн->кюн — «ю» после согласной; эрүл->эрул — «у».
#   һ: һалун->hалун — латинская h; Цаһан->Цаган — «г»; Таңһч->Тангч — пропуск.
#   җ: йовҗ->йовж — «ж»; Җаңһр->Джангар, ханҗанав->ханджанав — «дж».
#   ң: Таңһч->Тангч — «н»/«нг».

def _prev(word, i):
    return word[i - 1] if i > 0 else ''


def _sub(ch, prev, style, rnd):
    """Замена одной спецбуквы в выбранном стиле. style — dict буква->способ."""
    how = style[ch]
    if how == 'mix':
        how = rnd.choice(MIX_CHOICES[ch])
    after_c = prev in CONS
    if ch == 'ә':
        if how == 'soft':           # я после согласной и после ә/я, э в начале
            if prev == '' or prev in 'аоуыиэе':
                return 'э'
            return 'я'
        return {'a': 'а', 'e': 'э' if prev == '' else 'е', 'э': 'э'}[how]
    if ch == 'ө':
        if how == 'soft':
            return 'ё' if after_c and prev != 'й' else 'о'
        return 'о'
    if ch == 'ү':
        if how == 'soft':
            return 'ю' if after_c and prev != 'й' else 'у'
        return 'у'
    if ch == 'һ':
        return {'h': 'h', 'г': 'г', 'х': 'х', 'drop': ''}[how]
    if ch == 'җ':
        return {'ж': 'ж', 'дж': 'дж'}[how]
    if ch == 'ң':
        return {'н': 'н', 'нг': 'нг'}[how]
    raise KeyError(ch)


MIX_CHOICES = {'ә': ['soft', 'soft', 'a', 'e'], 'ө': ['soft', 'hard'],
               'ү': ['soft', 'hard'], 'һ': ['h', 'h', 'г', 'х'],
               'җ': ['ж', 'ж', 'дж'], 'ң': ['н', 'н', 'нг']}

# Стили — как пишет один человек в пределах текста. Писатель обычно
# последователен: кто пишет «бяядл», тот и «сян», и «кюн».
STYLES = {
    # «фонетический»: как в русской транскрипции калмыцких слов (самый частый)
    'soft_h':  {'ә': 'soft', 'ө': 'soft', 'ү': 'soft', 'һ': 'h', 'җ': 'ж', 'ң': 'н'},
    'soft_g':  {'ә': 'soft', 'ө': 'soft', 'ү': 'soft', 'һ': 'г', 'җ': 'ж', 'ң': 'н'},
    # «голый»: просто убрать хвостики — а, о, у, г/х, ж, н
    'bare':    {'ә': 'a', 'ө': 'hard', 'ү': 'hard', 'һ': 'г', 'җ': 'ж', 'ң': 'н'},
    'bare_h':  {'ә': 'a', 'ө': 'hard', 'ү': 'hard', 'һ': 'h', 'җ': 'ж', 'ң': 'н'},
    # ә -> э/е (так пишут те, кто слышит в ә «э»)
    'e_style': {'ә': 'e', 'ө': 'hard', 'ү': 'hard', 'һ': 'h', 'җ': 'ж', 'ң': 'н'},
    # «русская передача имён»: Джангар, Тангч
    'russian': {'ә': 'soft', 'ө': 'soft', 'ү': 'soft', 'һ': 'г', 'җ': 'дж', 'ң': 'нг'},
    # всё вперемешку в пределах одного текста
    'mixed':   {k: 'mix' for k in SPECIAL},
}

# Частичная порча: человек ставит спецбуквы, которые легко набрать (например,
# на телефоне долгим нажатием есть ө/ү, а ә нет), остальные заменяет.
PARTIAL = {
    'no_schwa':  {'ә'},                 # всё есть, кроме ә
    'no_h':      {'һ'},                 # всё есть, кроме һ
    'mongol_kb': {'ә', 'һ', 'җ', 'ң'},  # монгольская раскладка: только ө ү
    'kazakh_kb': {'җ'},                 # казахская раскладка: нет җ
}


def degrade(word, style='soft_h', rnd=None, keep=frozenset()):
    """Испортить одно слово (строчными). keep — какие спецбуквы человек
    всё-таки набирает."""
    rnd = rnd or random
    st = STYLES[style]
    out = []
    for i, ch in enumerate(word):
        if ch in SPECIAL and ch not in keep:
            # «после согласной» решаем по исходному слову
            out.append(_sub(ch, _prev(word, i), st, rnd))
        else:
            out.append(ch)
    return ''.join(out)


def degrade_text(text, style='soft_h', rnd=None, keep=frozenset()):
    rnd = rnd or random
    if style == 'mixed':
        # один «словарь привычек» на весь текст, иначе это не человек
        st = {k: rnd.choice(v) for k, v in MIX_CHOICES.items()}
        STYLES['_tmp'] = st
        style = '_tmp'

    def rep(m):
        w = m.group(0)
        low = w.lower()
        d = degrade(low, style, rnd, keep)
        if w[:1].isupper():
            d = d[:1].upper() + d[1:]
            if d[:1] == 'h':
                d = 'H' + d[1:] if rnd.random() < 0.5 else 'h' + d[1:]
        return d
    return re.sub(r'[А-Яа-яЁёӘәӨөҮүҺһҖҗҢң]+', rep, text)


# --------------------------------------------------------------------------
# Восстановление
# --------------------------------------------------------------------------
# Что в испорченном тексте может стоять на месте каждой спецбуквы.
REPLACEMENTS = {
    'ә': ['я', 'а', 'э', 'е'],
    'ө': ['о', 'ё'],
    'ү': ['у', 'ю'],
    'һ': ['һ', 'г', 'х', ''],   # 'һ' — латинская h после нормализации двойников
    'җ': ['ж', 'дж'],
    'ң': ['н', 'нг'],
}


def skeleton(w):
    """Ключ индекса: одинаков у правильного слова и у любой его порчи."""
    # «дж» и «нг» здесь не склеиваем: это могут быть и настоящие д+ж, н+г
    # (наадҗ -> наадж, миңһн -> мингн). Замены җ->дж и ң->нг ищутся
    # отдельным запросом, см. Restorer.candidates.
    w = w.replace('җ', 'ж').replace('ң', 'н')
    w = re.sub('[әяаэе]', 'a', w)
    w = re.sub('[өёо]', 'o', w)
    w = re.sub('[үюу]', 'u', w)
    w = re.sub('[һгх]', 'g', w)
    return w


def can_degrade_to(v, w):
    """Можно ли из правильного v получить w заменами из REPLACEMENTS."""
    from functools import lru_cache

    @lru_cache(None)
    def go(i, j):
        if i == len(v):
            return j == len(w)
        ch = v[i]
        if ch in REPLACEMENTS:
            opts = REPLACEMENTS[ch] + [ch]
        else:
            opts = [ch]
        for o in opts:
            if o == '' and ch == 'һ':
                if go(i + 1, j):
                    return True
                continue
            if w.startswith(o, j) and go(i + 1, j + len(o)):
                return True
        return False
    return go(0, 0)


class Restorer:
    def __init__(self, freq):
        self.freq = freq
        self.index = {}
        for v in freq:
            self.index.setdefault(skeleton(v), []).append(v)

    def candidates(self, w):
        """Правильные слова, из которых могла получиться запись w, по частоте."""
        keys = {skeleton(w)}
        for a, b in (('дж', 'ж'), ('нг', 'н')):
            if a in w:
                keys |= {skeleton(k.replace(a, b)) for k in (w, w.replace('дж', 'ж'))}
        out = {v for k in keys for v in self.index.get(k, ()) if can_degrade_to(v, w)}
        if not out and '-' in w:
            # составное слово: восстанавливаем части по отдельности
            parts = [(self.candidates(p) or [p])[0] for p in w.split('-')]
            joined = '-'.join(parts)
            return [joined] if joined != w else []
        return sorted(out, key=lambda v: -self.freq[v])


def normalize_lookalikes(text):
    """Двойники из других алфавитов -> калмыцкие буквы. Латинская h внутри
    кириллического слова — всегда һ; одиночная латиница (a, o, e, ...) внутри
    кириллического слова — её кириллический двойник."""
    text = unicodedata.normalize('NFC', text)

    def fix(m):
        tok = m.group(0)
        if not re.search('[а-яёА-ЯЁәөүһҗңӘӨҮҺҖҢ]', tok):
            return tok  # чисто латинское слово — транслитерация, не трогаем
        return ''.join(LOOKALIKE.get(c) or LATIN_TWINS.get(c) or c for c in tok)
    return re.sub(r"[\w'-]+", fix, text)
